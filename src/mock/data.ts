/**
 * HARD SEPARATION UTILITY:
 * Strips all internal and provider fields from internal order to produce customer-safe DTO.
 */
export function sanitizeForCustomer(order: InternalOrder): CustomerOrderDTO {
  const dueResult = computeDueTime(order.tier, new Date(order.createdAt), order.isAfterHours);
  return {
    id: order.id,
    token: order.token,
    property: order.property,
    tier: order.tier,
    status: order.status,
    createdAt: order.createdAt,
    customerDueTime: order.customerDueTime,
    dueTimeFormatted: dueResult.formatted,
    price: order.price,
    isAfterHours: order.isAfterHours,
    report: order.report,
    messages: order.messages,
  };
}

/**
 * HARD SEPARATION UTILITY:
 * Strips all customer identity and billing fields to produce provider-safe DTO.
 */
export function sanitizeForProvider(order: InternalOrder): ProviderOrderDTO {
  const internalDue = computeInternalDueTime(new Date(order.customerDueTime), order.tier);
  return {
    id: order.id,
    property: order.property,
    tier: order.tier,
    status: order.status,
    internalDueTime: order.internalDueTime,
    internalDueTimeFormatted: internalDue.formatted,
    providerPayout: order.providerPayout,
    assignedAt: order.assignedAt,
    report: order.report,
    messages: order.messages,
    customerRole: order.customer.role,
  };
}
